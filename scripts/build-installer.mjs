// Builds dist/install-lsum.ps1: a single self-contained installer (no clone needed) for sharing.
// It embeds the source files, writes them to a temp folder and runs the same steps as install.ps1.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n');
const files = ['skill/lsum.mjs', 'skill/SKILL.md', 'claude-md-snippet.md'];

const install = read('install.ps1');
const paramEnd = install.indexOf('\n)\n') + 3; // the param(...) block must stay first in a script
const param = install.slice(0, paramEnd);
const body = install.slice(paramEnd);

let embed = `# Self-contained build of install.ps1 (generated by scripts/build-installer.mjs - do not edit)\n`;
embed += `$LSUM_SRC = Join-Path $env:TEMP ('lsum-install-' + [guid]::NewGuid())\n`;
embed += `New-Item -ItemType Directory -Force -Path (Join-Path $LSUM_SRC 'skill') | Out-Null\n`;
for (const f of files) {
  const content = read(f).replace(/\n+$/, '');
  if (content.includes("\n'@")) throw new Error(`${f} contains a line starting with '@ and cannot be embedded`);
  embed += `[IO.File]::WriteAllText((Join-Path $LSUM_SRC '${f.replace(/\//g, '\\')}'), @'\n${content}\n'@ + "\`n", (New-Object System.Text.UTF8Encoding($false)))\n`;
}

const out = (param + embed + body).replace(/\n/g, '\r\n');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'install-lsum.ps1'), out);
console.log('wrote dist/install-lsum.ps1');
